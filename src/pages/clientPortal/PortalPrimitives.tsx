import React, { useEffect } from 'react';

/* ---------- Modal shell ---------- */
export function PortalModal({
  title,
  onClose,
  children,
  footer,
  wide,
  className,
  labelledBy,
}: {
  title?: React.ReactNode;
  onClose: () => void;
  children: React.ReactNode;
  footer?: React.ReactNode;
  wide?: boolean;
  className?: string;
  labelledBy?: string;
}) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', onKey);
    const prev = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
    return () => {
      window.removeEventListener('keydown', onKey);
      document.body.style.overflow = prev;
    };
  }, [onClose]);

  return (
    <div className="pp-overlay" onClick={onClose} role="presentation">
      <div
        className={`pp-modal pp-pop${wide ? ' pp-modal--wide' : ''}${className ? ` ${className}` : ''}`}
        role="dialog"
        aria-modal="true"
        aria-labelledby={labelledBy}
        onClick={(e) => e.stopPropagation()}
      >
        {title !== undefined ? (
          <div className="pp-modal-head">
            <h2 id={labelledBy}>{title}</h2>
            <button type="button" className="pp-modal-close" onClick={onClose} aria-label="Close">
              <Icon name="x" />
            </button>
          </div>
        ) : null}
        {children}
        {footer ? <div className="pp-modal-foot">{footer}</div> : null}
      </div>
    </div>
  );
}

